/* ============================================================
   SILICON RELICS — rendering
   Reads window.SR (data.js, generated by tools/build-data.mjs)
   and draws the catalogue. Content changes never touch this file.
   ============================================================ */

(function () {
  "use strict";

  const SR = window.SR;
  const GH = "https://github.com/" + SR.site.owner + "/";
  const R = SR.repos;
  const W = SR.workshop.items.map(w => Object.assign({ sec: "workshop" }, w));
  const PL = SR.platforms;
  const $ = s => document.querySelector(s);
  const esc = s => String(s == null ? "" : s).replace(/[&<>"']/g, c =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const plural = (n, one, many) => n + " " + (n === 1 ? one : (many || one + "s"));

  /* ---------- vocabulary ---------- */
  const SECTIONS = [
    ["recomp", "Recompilation"], ["ports", "Ports"], ["homebrew", "Homebrew"],
    ["tools", "Emulators & tools"], ["research", "Research"], ["docs", "Documentation"], ["workshop", "Workshop"]];
  const SEC_ORDER = SECTIONS.map(s => s[0]);
  const KIND = {
    kit: "Toolkit", "recomp-port": "Recompiled port", "source-port": "Source port", reimplementation: "Reimplementation",
    homebrew: "Homebrew", emulator: "Emulator", tool: "Tool", research: "Platform research", "re-notes": "Reverse engineering",
    "doc-title": "Write-up", "doc-index": "Index", "doc-platformnotes": "Checklist",
  };
  const STATUS = {
    complete: "Restored", playable: "Playable", "in-game": "In-game", boots: "Boots", analysis: "Under study",
    documented: "Catalogued", living: "Growing", ongoing: "In progress",
  };
  const ABBR = id => id.replace(/^[as](?=\d)/, "").toUpperCase().slice(0, 5);
  const CAP = 26; // timeline columns taller than this are cut

  /* ---------- derived ---------- */
  const machines = (() => {
    const ids = [...new Set(R.map(r => r.p).concat(W.map(w => w.p)))];
    const tail = ["multi", "original"];
    return ids.filter(k => !tail.includes(k))
      .sort((a, b) => (PL[a].y || 0) - (PL[b].y || 0) || PL[a].n.localeCompare(PL[b].n))
      .concat(tail.filter(k => ids.includes(k)));
  })();
  const portsOf = kit => R.filter(r => r.c === "recomp-port" && r.k === kit).sort((a, b) => a.cr.localeCompare(b.cr));
  const bornHere = new Set(R.filter(r => r.c === "kit").map(k => (portsOf(k.r)[0] || {}).r).filter(Boolean));
  const kitsOf = new Set(R.filter(r => r.c === "kit").map(r => r.r));
  const byId = new Map(R.map(r => [r.r, r]).concat(W.map(w => [w.id, w])));
  const pName = id => (PL[id] ? PL[id].n : id);

  const state = { f: "all", q: "", open: {} };

  /* ---------- masthead, figures, timeline ---------- */
  function renderHead() {
    const realMachines = machines.filter(m => m !== "multi" && m !== "original");
    const years = realMachines.map(m => PL[m].y).filter(Boolean);
    $("#intro").innerHTML =
      `A catalogue of <b>${R.length}</b> public repositories and <b>${W.length}</b> pieces still in the workshop, ` +
      `across <b>${realMachines.length}</b> machines from ${Math.min(...years)} to ${Math.max(...years)}: games recompiled ` +
      `to run natively on PC, ports to consoles they never ran on, emulators, homebrew, and the documentation of what is on the discs. ` +
      `The bar under each object says how far it has come.`;

    const kits = R.filter(r => r.c === "kit").length;
    const ports = R.filter(r => /port|reimpl/.test(r.c));
    const playing = ports.filter(r => r.s === "playable" || r.s === "complete").length;
    const emus = R.filter(r => r.c === "emulator").length;
    const docs = R.filter(r => r.sec === "docs").length;
    $("#figures").innerHTML = [
      [R.length, "public repositories"], [realMachines.length, "machines"], [kits, "recompilation toolkits"],
      [playing + " / " + ports.length, "ports that play"], [emus, "emulators"], [docs, "write-ups"],
    ].map(([n, l]) => `<div><b>${n}</b><span>${l}</span></div>`).join("");

    $("#tl").innerHTML = `<div class="tl-grid">${machines.map(m => {
      const w = R.filter(r => r.p === m && r.sec !== "docs").length;
      const k = W.filter(x => x.p === m).length;
      const d = R.filter(r => r.p === m && r.sec === "docs").length;
      const n = w + k + d, H = Math.max(3, Math.round(Math.min(n, CAP) / CAP * 124));
      const px = x => (n ? Math.max(x ? 2 : 0, Math.round(x / n * H)) : 0);
      const P = PL[m];
      return `<button class="tl-col" data-room="${m}" title="${esc(P.n)}: ${plural(w, "work")}, ${k} in the workshop, ${plural(d, "write-up")}">` +
        `<em>${n}</em><span class="stk${n > CAP ? " cut" : ""}" style="height:${H}px">` +
        (w ? `<i class="w" style="height:${px(w)}px"></i>` : "") +
        (k ? `<i class="k" style="height:${px(k)}px"></i>` : "") +
        (d ? `<i class="d" style="height:${px(d)}px"></i>` : "") +
        `</span><span class="lab">${P.y || "—"} ${esc(P.n)}</span></button>`;
    }).join("")}</div>`;
    $("#tl-cap").textContent = `Columns over ${CAP} are cut and keep their real count on top`;

    const lately = R.slice().sort((a, b) => b.cr.localeCompare(a.cr)).slice(0, 6);
    $("#lately").innerHTML = lately.map(r =>
      `<button type="button" data-open="${esc(r.r)}"><span class="d">${r.cr.slice(0, 10)}</span><b>${esc(r.t)}</b><span class="m">${esc(KIND[r.c])} · ${esc(pName(r.p))}</span></button>`).join("");

    $("#ws-asof").textContent = SR.workshop.asof;
    $("#since").textContent = SR.site.since;
    $("#updated").textContent = SR.site.updated;
    if (SR.site.kofi) $("#kofi").innerHTML = `If this work is useful to you, you can support it on <a href="${esc(SR.site.kofi)}" target="_blank" rel="noopener">Ko-fi</a>.`;
  }

  /* ---------- filters ---------- */
  function matches(o) {
    if (state.f !== "all" && o.sec !== state.f) return false;
    if (!state.q) return true;
    const hay = [o.t, o.r || "", o.g, o.k || "", pName(o.p), PL[o.p] ? PL[o.p].mk : "", KIND[o.c] || ""].join(" ").toLowerCase();
    return state.q.split(/\s+/).every(w => hay.includes(w));
  }
  function renderChips() {
    const n = k => (k === "all" ? R.length + W.length : k === "workshop" ? W.length : R.filter(r => r.sec === k).length);
    $("#chips").innerHTML = [["all", "Everything"]].concat(SECTIONS).map(([k, l]) =>
      `<button type="button" class="chip" data-f="${k}" aria-pressed="${state.f === k}">${l}<span class="n">${n(k)}</span></button>`).join("");
  }

  /* ---------- labels ---------- */
  const bar = v => `<div class="bar-t"><i style="width:${v}%"></i></div>`;

  function repoLabel(r, acc) {
    const shot = r.shots && r.shots[0];
    const tags = [];
    if (r.c === "kit") { const n = portsOf(r.r).length; tags.push(n ? plural(n, "port") + " built on it" : "a whole library at once"); }
    if (r.k && r.c !== "kit") tags.push("on " + r.k);
    const born = bornHere.has(r.r);
    return `<button type="button" class="label" data-open="${esc(r.r)}">` +
      (shot ? `<span class="shot${r.px ? " px" : ""}"><img src="${esc(shot)}" alt="" loading="lazy"></span>` : "") +
      (r.v >= 100 ? `<span class="stamp">RESTORED</span>` : "") +
      (r.icon && !shot ? `<img class="ico" src="${esc(r.icon)}" alt="" loading="lazy">` : "") +
      `<span class="acc">${acc}</span><span class="kind">${esc(KIND[r.c])}</span>` +
      `<h3>${esc(r.t)}</h3><p>${esc(r.g)}</p>` +
      (tags.length || born ? `<span class="tags">${born ? `<span class="tag born">Born here</span>` : ""}${tags.map(t => `<span class="tag">${esc(t)}</span>`).join("")}</span>` : "") +
      `<span class="rest">${bar(r.v)}<span class="row"><span>${esc(STATUS[r.s] || r.s)} · ${esc(r.m || "")}</span><b>${r.v}%</b></span></span></button>`;
  }
  function workLabel(w, acc) {
    const sealed = w.p === "original";
    const shot = w.shots && w.shots[0];
    const inner =
      (shot ? `<span class="shot px"><img src="${esc(shot)}" alt="" loading="lazy"></span>` : "") +
      (w.v >= 100 ? `<span class="stamp">RESTORED</span>` : "") +
      `<span class="acc">${acc}</span><span class="kind">${sealed ? "Original game · in the making" : "In the workshop · not yet published"}</span>` +
      `<h3>${esc(w.t)}</h3><p>${esc(w.g)}</p>` +
      `<span class="rest">${bar(w.v)}<span class="row"><span>${w.s === "complete" ? "Restored" : "In progress"} · as of ${SR.workshop.asof}</span><b>${w.v}%</b></span></span>`;
    return sealed ? `<div class="label sealed">${inner}</div>`
      : `<button type="button" class="label wk" data-open="${esc(w.id)}">${inner}</button>`;
  }
  function docRow(d) {
    const extra = d.c !== "doc-title" ? ` <small>${KIND[d.c]}</small>` : d.y ? ` <small>${d.y}</small>` : "";
    return `<button type="button" data-open="${esc(d.r)}"><span>${esc(d.t)}${extra}</span><b>${d.v}%</b></button>`;
  }
  const era = y => (!y ? "Undated" : y < 1990 ? "Before 1990" : y < 2000 ? "The 1990s" : y < 2010 ? "The 2000s" : "2010 and later");

  /* ---------- rooms ---------- */
  function renderRooms() {
    let html = "", shown = 0;
    const filtering = state.f !== "all" || state.q;
    machines.forEach(m => {
      const P = PL[m];
      const objs = R.filter(r => r.p === m && r.sec !== "docs" && matches(r)).sort((a, b) =>
        SEC_ORDER.indexOf(a.sec) - SEC_ORDER.indexOf(b.sec) || (b.c === "kit") - (a.c === "kit") ||
        (a.k && kitsOf.has(a.k) ? a.k : "").localeCompare(b.k && kitsOf.has(b.k) ? b.k : "") || b.v - a.v);
      const wk = W.filter(w => w.p === m && matches(w)).sort((a, b) => b.v - a.v);
      const docs = R.filter(r => r.p === m && r.sec === "docs" && matches(r))
        .sort((a, b) => (b.c !== "doc-title") - (a.c !== "doc-title") || a.t.localeCompare(b.t));
      const n = objs.length + wk.length + docs.length;
      if (!n) return;
      shown += n;
      const parts = [objs.length && plural(objs.length, "work"), wk.length && wk.length + " in the workshop",
        docs.length && plural(docs.length, "write-up")].filter(Boolean).join(" · ");
      html += `<section class="room" id="room-${m}" aria-labelledby="h-${m}"><div class="placard">` +
        `<span class="yr">${P.y || (m === "original" ? "★" : "∞")}</span>` +
        `<div><h2 id="h-${m}">${esc(P.n)}</h2><span class="mk">${esc(P.mk || "")}</span></div><span class="ct">${parts}</span></div>`;

      let i = 0;
      const acc = w => `SR·${P.y || "0000"}·${ABBR(m)}·${w ? "W" : ""}${String(++i).padStart(3, "0")}`;
      if (objs.length || wk.length)
        html += `<div class="labels">${objs.map(r => repoLabel(r, acc())).join("")}` +
          `${wk.map(w => workLabel(w, m === "original" ? "SR·OPUS·SEALED" : acc(true))).join("")}</div>`;

      if (docs.length) {
        const open = state.open[m] || filtering;
        let rows = "";
        if (open && docs.length > 12) {
          const idx = docs.filter(d => d.c !== "doc-title");
          if (idx.length) rows += `<div class="era">Index &amp; checklist</div>` + idx.map(docRow).join("");
          ["Before 1990", "The 1990s", "The 2000s", "2010 and later", "Undated"].forEach(e => {
            const g = docs.filter(d => d.c === "doc-title" && era(d.y) === e);
            if (g.length) rows += `<div class="era">${e} · ${g.length}</div>` + g.map(docRow).join("");
          });
        } else rows = (open ? docs : docs.slice(0, 6)).map(docRow).join("");
        const more = docs.length > 6 && !filtering
          ? `<button type="button" class="shelf-more" data-shelf="${m}" aria-expanded="${!!open}">${open ? "Show fewer" : "Show all " + docs.length + " write-ups" + (docs.length > 12 ? ", by decade" : "")}</button>` : "";
        html += `<div class="shelf"><h4>Documentation shelf · ${docs.length}</h4><div class="shelf-grid">${rows}</div>${more}</div>`;
      }
      html += `</section>`;
    });
    $("#rooms").innerHTML = html || `<p class="empty">Nothing in the catalogue matches. Clear the search or pick another kind.</p>`;
    $("#count").textContent = filtering ? `${shown} of ${R.length + W.length} shown` : `${R.length + W.length} objects`;
  }

  /* ---------- card dialog ---------- */
  function openCard(id) {
    const o = byId.get(id);
    if (!o) return;
    const isRepo = !!o.r;
    const P = PL[o.p] || { n: o.p };
    const sub = [P.n, o.y, o.mk].filter(Boolean).map(esc).join(" · ");
    const shots = (o.shots || []).map(s =>
      `<a href="${esc(s)}" target="_blank" rel="noopener"${o.px || !isRepo ? ' class="px"' : ""}><img src="${esc(s)}" alt="Screenshot of ${esc(o.t)}" loading="lazy"></a>`).join("");
    let body = `<div class="dlg-top"><div><span class="kind">${isRepo ? esc(KIND[o.c]) + (o.k && o.c !== "kit" ? " · on " + esc(o.k) : "") : "In the workshop · not yet published"}</span>` +
      `<h2 id="card-title">${esc(o.t)}</h2><span class="sub">${sub}</span></div>` +
      `<button type="button" class="x" data-close>Close</button></div>`;
    body += `<p>${esc(isRepo ? o.su || o.g : o.g)}</p>`;
    if (isRepo && o.f) body += `<p class="first">${esc(o.f)}</p>`;
    if (isRepo && o.h && o.h.length) body += `<ul>${o.h.map(h => `<li>${esc(h)}</li>`).join("")}</ul>`;
    if (isRepo && o.c === "kit") {
      const ps = portsOf(o.r);
      if (ps.length) body += `<ul>${ps.map((p, j) => `<li><a href="#${esc(p.r)}" data-open="${esc(p.r)}">${esc(p.t)}</a> — ${esc(STATUS[p.s])}, ${p.v}%${j === 0 ? " · born here" : ""}</li>`).join("")}</ul>`;
    }
    body += `<div class="meter"><div class="top"><b>${o.v}%</b><span>${esc(isRepo ? (STATUS[o.s] || o.s) + " · " + (o.m || "") : "In progress · as of " + SR.workshop.asof)}</span></div>${bar(o.v)}` +
      (isRepo && o.b ? `<p>${esc(o.b)}</p>` : "") + `</div>`;
    if (shots) body += `<div class="gallery">${shots}</div>`;
    body += isRepo
      ? `<div class="dlg-foot"><span class="meta">${esc(o.r)} · created ${o.cr.slice(0, 10)} · last push ${o.pu}</span><a class="go" href="${GH + esc(o.r)}" target="_blank" rel="noopener">Open on GitHub ↗</a></div>`
      : `<div class="dlg-foot"><span class="meta">Kept off GitHub for now.</span></div>`;
    $("#card-body").innerHTML = body;
    const dlg = $("#card");
    if (!dlg.open) dlg.showModal();
    $("#card-body").scrollTop = 0;
    if (location.hash.slice(1) !== id) history.replaceState(null, "", "#" + id);
  }
  function closeCard() {
    const dlg = $("#card");
    if (dlg.open) dlg.close();
  }

  /* ---------- events ---------- */
  function wire() {
    document.addEventListener("click", e => {
      const op = e.target.closest("[data-open]");
      if (op) { e.preventDefault(); openCard(op.dataset.open); return; }
      if (e.target.closest("[data-close]")) { closeCard(); return; }
      const col = e.target.closest(".tl-col");
      if (col) {
        if (state.f !== "all" || state.q) { state.f = "all"; state.q = ""; $("#q").value = ""; renderChips(); renderRooms(); }
        const el = document.getElementById("room-" + col.dataset.room);
        if (el) el.scrollIntoView();
        return;
      }
      const chip = e.target.closest(".chip");
      if (chip) { state.f = chip.dataset.f; renderChips(); renderRooms(); return; }
      const sh = e.target.closest("[data-shelf]");
      if (sh) {
        const m = sh.dataset.shelf;
        state.open[m] = !state.open[m];
        renderRooms();
        if (!state.open[m]) { const el = document.getElementById("room-" + m); if (el && el.getBoundingClientRect().top < 0) el.scrollIntoView(); }
      }
    });
    const dlg = $("#card");
    dlg.addEventListener("click", e => { if (e.target === dlg) closeCard(); });
    dlg.addEventListener("close", () => {
      if (byId.has(location.hash.slice(1))) history.replaceState(null, "", location.pathname + location.search);
    });
    let t;
    $("#q").addEventListener("input", e => {
      clearTimeout(t);
      t = setTimeout(() => { state.q = e.target.value.trim().toLowerCase(); renderRooms(); }, 120);
    });
    window.addEventListener("hashchange", fromHash);
  }
  function fromHash() {
    const h = decodeURIComponent(location.hash.slice(1));
    if (byId.has(h)) openCard(h);
  }

  renderHead();
  renderChips();
  renderRooms();
  wire();
  fromHash();
})();
